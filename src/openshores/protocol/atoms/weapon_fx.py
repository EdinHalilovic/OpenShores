_WEAPON_EFFECT_DEFAULTS = {
    (0x08, 1): (0x5F, 0x1E),
    (0x08, 2): (0x5F, 0x1E),
    (0x09, 1): (0x5F, 0x1E),
    (0x09, 2): (0x5F, 0x1E),
    (0x0C, 1): (0x5F, 0x1E),
    (0x0C, 2): (0x5F, 0x1E),
}

_WEAPON_RANGED_FX_BY_CID = {
    31:  (0x21, 7),
    32:  (0x22, 8),
    117: (0x23, 9),
    292: (0x1C, 8),
    296: (0x1F, 5),
    305: (0x1F, 5),
}


def _swing_fx_for_weapon(cid: int, sub_mode: int):
    if int(sub_mode) == 0:
        return (0x5F, 0x1E)
    return _WEAPON_RANGED_FX_BY_CID.get(int(cid) & 0xFFFF, (0x5F, 0x1E))


